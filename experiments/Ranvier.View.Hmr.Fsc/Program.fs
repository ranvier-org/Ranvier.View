/// A fingerprinting F# compiler for dev builds. MSBuild runs it in place of fsc.dll
/// (DotnetFscCompilerPath). It compiles with the fickle FCS (the same compiler the dev host's FSI uses) and
/// embeds a stamp per top-level declaration as AssemblyMetadata, so the running app describes its own code.
module Ranvier.View.Hmr.Fsc

open System
open System.IO
open System.Text
open FSharp.Compiler.CodeAnalysis
open FSharp.Compiler.Diagnostics
open Ranvier.View.WebCore.Hmr

let private expand (argv: string array) =
    [|
        for a in argv do
            if a.StartsWith "@" then
                for line in File.ReadAllLines (a.Substring 1) do
                    let l = line.Trim ()

                    if l <> "" then
                        yield
                            (if
                                 l.Length > 1
                                 && l.StartsWith "\""
                                 && l.EndsWith "\""
                             then
                                 l.Substring (1, l.Length - 2)
                             else
                                 l)
            else
                yield a
    |]

let private isSource (a: string) =
    not (a.StartsWith "-")
    && a.EndsWith (".fs", StringComparison.OrdinalIgnoreCase)

let private literal (s: string) =
    "\""
    + s.Replace("\\", "\\\\").Replace("\"", "\\\"")
    + "\""

[<EntryPoint>]
let main argv =
    // MSBuild runs the compiler in the project folder and passes sources relative to it.
    let args =
        expand argv
        |> Array.map (fun a -> if isSource a then Path.GetFullPath a else a)

    let out =
        args
        |> Array.tryPick (fun a ->
            if a.StartsWith "-o:" then Some (a.Substring 3)
            elif a.StartsWith "--out:" then Some (a.Substring 6)
            else None)

    let sources = args |> Array.filter isSource

    // Stamps go first in compile order: an exe's last file must hold the entry point.
    let stampFile =
        let dir =
            match out with
            | Some o -> Path.GetDirectoryName (Path.GetFullPath o)
            | None -> Path.GetTempPath ()

        Path.Combine (dir, "HmrStamps.g.fs")

    File.WriteAllLines (Path.ChangeExtension (stampFile, ".args.txt"), args)
    let sb = StringBuilder ()

    sb.AppendLine("// Generated by Ranvier.View.Hmr.Fsc: one stamp per top-level declaration.").AppendLine("module internal HmrStamps")
    |> ignore

    sb.AppendLine ($"[<assembly: System.Reflection.AssemblyMetadata({literal Stamps.compilerKey}, \"fickle\")>]")
    |> ignore

    let sw = Diagnostics.Stopwatch.StartNew ()

    let projectFile =
        match Directory.GetFiles (Environment.CurrentDirectory, "*.fsproj") with
        | [| p |] -> p
        | _ -> Path.Combine (Environment.CurrentDirectory, "project.fsproj")

    let ctx = Stamps.context projectFile args

    for s in sources do
        let file = Path.GetFileName s

        for st in Stamps.ofFile ctx s do
            let key = literal (Stamps.prefix + file + ":" + st.Key)
            let value = literal $"{st.Hash}|{st.StartLine}|{st.EndLine}"

            sb.AppendLine ($"[<assembly: System.Reflection.AssemblyMetadata({key}, {value})>]")
            |> ignore

    sb.AppendLine "do ()" |> ignore
    File.WriteAllText (stampFile, sb.ToString ())

    // Hosted as a library, FCS looks for its default Win32 manifest beside the runtime; the SDK keeps it beside fsc.dll.
    let manifest =
        if
            args
            |> Array.exists (fun a ->
                a.StartsWith "--win32manifest"
                || a = "--nowin32manifest")
        then
            [||]
        else
            let sdk =
                Path.Combine (Path.GetDirectoryName (typeof<obj>.Assembly.Location), "..", "..", "..", "sdk")

            let found =
                if Directory.Exists sdk then
                    Directory.GetFiles (sdk, "default.win32manifest", SearchOption.AllDirectories)
                    |> Array.tryLast
                else
                    None

            match found with
            | Some m -> [| "--win32manifest:" + Path.GetFullPath m |]
            | None -> [| "--nowin32manifest" |]

    let firstSource = args |> Array.findIndex isSource

    let compileArgs =
        Array.concat
            [
                [| "fsc.exe" |]
                manifest
                args[.. firstSource - 1]
                [| stampFile |]
                args[firstSource..]
            ]

    let stampMs = sw.Elapsed.TotalMilliseconds
    sw.Restart ()

    let diagnostics, failure =
        FSharpChecker.Create().Compile compileArgs
        |> Async.RunSynchronously

    Console.WriteLine
        $"Ranvier.View.WebCore.Hmr.Fsc: stamped {sources.Length} files in {stampMs:F0} ms, compiled in {sw.Elapsed.TotalMilliseconds:F0} ms (fickle FCS)"

    for d in diagnostics do
        let severity =
            match d.Severity with
            | FSharpDiagnosticSeverity.Error -> "error"
            | FSharpDiagnosticSeverity.Warning -> "warning"
            | _ -> "info"

        if severity <> "info" then
            Console.Error.WriteLine $"{d.FileName}({d.StartLine},{d.StartColumn + 1}): {severity} FS{d.ErrorNumber:D4}: {d.Message}"

    match failure with
    | Some e ->
        Console.Error.WriteLine $"error FS0000: {e.Message}"
        1
    | None when
        diagnostics
        |> Array.exists (fun d -> d.Severity = FSharpDiagnosticSeverity.Error)
        ->
        1
    | None -> 0
