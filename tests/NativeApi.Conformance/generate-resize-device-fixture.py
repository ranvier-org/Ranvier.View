"""Generate the shared device-pixel fixture from the native lane's measured oracle."""
import argparse
import hashlib
import json
from pathlib import Path


def generate(cases_path, oracle_path, native_css_path):
    cases_bytes, oracle_bytes, native_bytes = cases_path.read_bytes(), oracle_path.read_bytes(), native_css_path.read_bytes()
    cases, oracle, native = json.loads(cases_bytes), json.loads(oracle_bytes), json.loads(native_bytes)
    assert hashlib.sha256(native_bytes).hexdigest() == '23ef0c171e763e689a5192a8dabc5c33ec10a04993b0fd41512ac4f60eb68d7b'
    assert native['source'] == '81da36620969e3bc268de4e78bc1659696cf12e9'
    assert native['packageSha256'] == '9200a671148d39ccdb83c880aa8358dc348633152936fec2acdaf21e4446798b'
    assert native['hostSha256'] == 'c59c46d4bee89db84665793fd3bb9e899b2600b2ef2da17eeb0a7159899dd7cf'
    selected = [case for case in cases['scenarios'] if case['name'].startswith('devicePixel')]
    assert len(selected) == 8

    def string(value):
        return json.dumps(value, ensure_ascii=False)

    def array(values):
        return '[| ' + '; '.join(values) + ' |]'

    def numbers(values):
        return array([repr(float(value)) for value in values])

    lines = [
        'module internal NativeApiConformance.ResizeDevicePixelData', '',
        '/// <summary>A measured delivery, including CSS geometry and its device-pixel box.</summary>',
        'type Entry = string * string * float array', '',
        '/// <summary>Ordered mutations, Chromium device sizes and per-engine CSS measurements.</summary>',
        'type Case = { Name: string; Steps: string array array; Log: string array; Entries: Entry array; NativeCss: Entry array }', '',
        '// Generated by generate-resize-device-fixture.py; Chromium ' + oracle['browser'] + '.',
        '// Input SHA256: cases=' + hashlib.sha256(cases_bytes).hexdigest(),
        '// Input SHA256: oracle=' + hashlib.sha256(oracle_bytes).hexdigest(), '',
        '// Native CSS snapshot SHA256: ' + hashlib.sha256(native_bytes).hexdigest(),
        '/// <summary>The complete measured page used by the device-pixel cases.</summary>',
        'let markup = ' + string(cases['markup']), '',
        '/// <summary>Returns all eight device-pixel cases measured at scale 1, 1.5 or 2.</summary>',
        'let cases scale : Case array =', '    match scale with',
    ]
    entry_count = 0
    for scale in ('1', '1.5', '2'):
        lines += ['    | ' + repr(float(scale)) + ' -> [|']
        for case in selected:
            measured = oracle['scales'][scale][case['name']]
            assert measured['statuses'] and set(measured['statuses']) == {'ok'}
            native_case = native['results'][scale][case['name']]
            assert native_case['log'] == measured['log']
            assert native_case['statuses'] == measured['statuses']
            assert len(native_case['entries']) == len(measured['entries'])
            lines += ['        { Name = ' + string(case['name']),
                      '          Steps = ' + array([array([string(part) for part in step]) for step in case['steps']]),
                      '          Log = ' + array([string(item) for item in measured['log']]),
                      '          Entries = [|']
            for entry in measured['entries']:
                values = entry['rect'] + entry['content'] + entry['border'] + entry['device']
                lines += ['              ' + string(entry['o']) + ', ' + string(entry['t']) + ', ' + numbers(values)]
            lines += ['          |]', '          NativeCss = [|']
            for expected, entry in zip(measured['entries'], native_case['entries']):
                assert (expected['o'], expected['t']) == (entry['o'], entry['t'])
                assert expected['device'] == entry['device']
                values = entry['rect'] + entry['content'] + entry['border']
                assert len(values) == 8
                entry_count += 1
                lines += ['              ' + string(entry['o']) + ', ' + string(entry['t']) + ', ' + numbers(values)]
            lines += ['          |] }']
        lines += ['        |]']
    assert entry_count == 105
    lines += ['    | _ -> invalidArg (nameof scale) "The resize oracle measures scales 1, 1.5 and 2."', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--cases', type=Path, required=True)
    parser.add_argument('--oracle', type=Path, required=True)
    parser.add_argument('--native-css', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    args.output.write_text(generate(args.cases, args.oracle, args.native_css), encoding='utf-8', newline='\n')
