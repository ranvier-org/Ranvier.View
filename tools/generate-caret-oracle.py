"""Writes tests/NativeApi.Conformance/CaretOracle.fs from Ranvier.WebCore's tests/fixtures/caret-hit-oracle.json (Chromium
156) and tests/fixtures/caret-hit-qualified.json (the native engine's measured differences).

Usage: python -I tools/generate-caret-oracle.py <Ranvier.WebCore checkout>"""
import hashlib
import json
from pathlib import Path
import sys

here = Path(__file__).resolve().parents[1]


def number(value):
    value = float(value)
    return str(int(value)) if value == int(value) else f'{value:.2f}'


def node(n):
    if n['kind'] == 'text':
        return f"text:{n['parent']}#{n['index']}@{n['scope']}"
    return f"{n['name']}#{n['id'] or ''}@{n['scope']}"


def outcome(value, rect=True):
    """The fixture's text form of a hit: null, a thrown error, or node:offset with the caret rectangle."""
    if value is None:
        return 'null'
    if 'error' in value:
        return 'throws ' + value['error']
    text = node(value['node']) + ':' + str(value['offset'])
    if rect:
        r = value.get('rect')
        text += ' [null]' if r is None else ' [' + ','.join(number(r[k]) for k in ['x', 'y', 'width', 'height']) + ']'
    return text


def fs(value):
    return json.dumps(value)


def main(webcore):
    webcore = Path(webcore)
    oracle_path, qualified_path = webcore / 'tests/fixtures/caret-hit-oracle.json', webcore / 'tests/fixtures/caret-hit-qualified.json'
    oracle, qualified = json.loads(oracle_path.read_text()), json.loads(qualified_path.read_text())
    scale = oracle['scales'][0]
    cases = [c for c in oracle['cases'] if c['scale'] == scale]
    for c in oracle['cases']:
        twin = next(x for x in cases if x['scroll'] == c['scroll'])
        assert [{k: h[k] for k in ['position', 'shadowRoots', 'range']} for h in c['hits']] == \
               [{k: h[k] for k in ['position', 'shadowRoots', 'range']} for h in twin['hits']], 'Chromium differs by scale: ' + c['scroll']
    lines = ['// Generated by tools/generate-caret-oracle.py from Ranvier.WebCore tests/fixtures/caret-hit-oracle.json',
             f"// (sha256 {hashlib.sha256(oracle_path.read_bytes()).hexdigest()[:16]}) and caret-hit-qualified.json",
             f"// (sha256 {hashlib.sha256(qualified_path.read_bytes()).hexdigest()[:16]}). Do not edit.",
             'module internal NativeApiConformance.CaretOracle', '',
             '/// <summary>The Chromium browser version that recorded the oracle.</summary>',
             f"let browser = {fs(oracle['browser'])}", '',
             '/// <summary>Device scales; Chromium gives the same outcomes at each.</summary>',
             'let scales = [ ' + '; '.join(number(s) + '.0' if float(s) == int(s) else str(s) for s in oracle['scales']) + ' ]', '',
             '/// <summary>Hit points: name, x and y in CSS pixels of the viewport; NaN and infinities are non-finite cases.</summary>',
             'let points =', '    ['
             ]
    literal = lambda v: {'NaN': 'nan', 'Infinity': 'infinity', '-Infinity': '-infinity'}[v] if isinstance(v, str) else (number(v) + ('.0' if float(v) == int(v) else ''))
    for name, x, y in oracle['points']:
        lines.append(f'        {fs(name)}, {literal(x)}, {literal(y)}')
    lines += ['    ]', '', '/// <summary>Requested scrolls: name, left and top.</summary>', 'let scrolls =', '    [']
    for name, x, y in oracle['scrolls']:
        lines.append(f'        {fs(name)}, {literal(x)}, {literal(y)}')
    lines += ['    ]', '',
              '/// <summary>Chromium outcomes keyed by the actual scroll offset ("x,y"), then point name: position, with shadowRoots, and caretRangeFromPoint.</summary>',
              'let expected =', '    Map.ofList', '        [']
    for c in cases:
        lines.append(f"            {fs(number(c['scrollX']) + ',' + number(c['scrollY']))},")
        lines.append('            Map.ofList')
        lines.append('                [')
        for h in c['hits']:
            lines.append(f"                    {fs(h['name'])}, ({fs(outcome(h['position']))}, {fs(outcome(h['shadowRoots']))}, {fs(outcome(h['range'], False))})")
        lines.append('                ]')
    lines += ['        ]', '',
              '/// <summary>A held CaretPosition per Chromium: offset, isConnected, data and rectangle, before and after the text shrinks and is removed.</summary>',
              'let lifetime =', '    [']
    life = oracle['lifetime'][0]
    for step in ['before', 'shortened', 'removed']:
        s = life[step]
        rect = '[' + ','.join(number(s['rect'][k]) for k in ['x', 'y', 'width', 'height']) + ']'
        lines.append(f"        {fs(step)}, ({s['offset']}u, {str(s['connected']).lower()}, {fs(s['data'])}, {fs(rect)})")
    lines += ['    ]', '',
              '/// <summary>The native engine\'s measured differences: "scroll|point|member" to the native outcome.</summary>',
              'let nativeQualified =', '    Map.ofList', '        [']
    seen = {}
    for d in qualified['differences']:
        if d['scroll'] == 'held':
            r = d['native']
            value = '[' + ','.join(number(r[k]) for k in ['x', 'y', 'width', 'height']) + ']'
        else:
            value = outcome(d['native'], d['member'] != 'range')
        key = (d['scroll'], d['point'], d['member'])
        assert seen.get(key, value) == value, 'a qualified difference depends on the scale: ' + str(key)
        seen[key] = value
    for (scroll, point, member), value in sorted(seen.items()):
        lines.append(f'            {fs(scroll + "|" + point + "|" + member)}, {fs(value)}')
    lines += ['        ]', '']
    (here / 'tests/NativeApi.Conformance/CaretOracle.fs').write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print('CaretOracle.fs:', len(oracle['points']), 'points,', len(cases), 'scroll offsets,', len(seen), 'native qualifications')


if __name__ == '__main__':
    main(sys.argv[1])
