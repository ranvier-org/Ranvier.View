module RanvierHtmlTagMetadata

open System
open System.Reflection
open System.Text.Json

/// <summary>Checks canonical WebKit tag identities against existing typed HTML authoring.</summary>
let validate (browserAssembly: Assembly) (sharedAssembly: Assembly) (metadata: JsonElement) =
    let tags =
        metadata.GetProperty("tagInterfaces").EnumerateArray()
        |> Seq.toArray

    let html =
        tags
        |> Array.filter (fun row -> row.GetProperty("namespaceURI").GetString() = "http://www.w3.org/1999/xhtml")
        |> Array.map (fun row -> row.GetProperty("tag").GetString(), row.GetProperty("interface").GetString())
        |> dict

    for property in browserAssembly.GetType("Fable.Core.TS+Dom+HTMLElementTagNameMap", true).GetProperties() do
        match html.TryGetValue property.Name with
        | true, name when name = property.PropertyType.Name -> ()
        | _ -> invalidOp $"WebKit HTML tag identity differs from authoring: {property.Name}"

    for row in tags do
        sharedAssembly.GetType (
            "Ranvier.Dom."
            + row.GetProperty("interface").GetString(),
            true
        )
        |> ignore

/// <summary>Renders concrete HTML and SVG interface names from canonical WebKit tag metadata.</summary>
let render (metadata: JsonElement) =
    let tags =
        metadata.GetProperty("tagInterfaces").EnumerateArray()
        |> Seq.toArray

    let lines = ResizeArray<string>()
    lines.Add "// <auto-generated> tools/Ranvier.Dom.Generate; regenerate instead of editing. </auto-generated>"
    lines.Add "module internal Ranvier.View.Twin.TagTypes"
    lines.Add ""

    for family, uri in [ "html", "http://www.w3.org/1999/xhtml"; "svg", "http://www.w3.org/2000/svg" ] do
        lines.Add $"let private {family} ="
        lines.Add "    dict ["

        for row in
            tags
            |> Array.filter (fun row -> row.GetProperty("namespaceURI").GetString() = uri)
            |> Array.sortBy (fun row -> row.GetProperty("tag").GetString()) do
            let tag, name =
                row.GetProperty("tag").GetString(), row.GetProperty("interface").GetString()

            lines.Add $"        \"{tag}\", \"{name}\""

        lines.Add "    ]"
        lines.Add ""

    lines.Add "let interfaceName namespaceName tag ="
    lines.Add "    if namespaceName = \"math\" then \"Element\""
    lines.Add "    else"
    lines.Add "        let names, fallback = if namespaceName = \"svg\" then svg, \"SVGElement\" else html, \"HTMLElement\""
    lines.Add "        match names.TryGetValue tag with"
    lines.Add "        | true, name -> name"
    lines.Add "        | _ -> fallback"
    String.concat "\n" lines + "\n"
