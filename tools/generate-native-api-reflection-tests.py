import argparse
import json
import pathlib

TAGS = {"HTMLBaseElement":["base"],"HTMLBRElement":["br"],"HTMLDataElement":["data"],"HTMLDataListElement":["datalist"],"HTMLDirectoryElement":["dir"],"HTMLDListElement":["dl"],"HTMLFontElement":["font"],"HTMLHeadingElement":["h1","h6"],"HTMLHRElement":["hr"],"HTMLHtmlElement":["html"],"HTMLMapElement":["map"],"HTMLMarqueeElement":["marquee"],"HTMLMenuElement":["menu"],"HTMLMetaElement":["meta"],"HTMLModElement":["del","ins"],"HTMLParamElement":["param"],"HTMLPictureElement":["picture"],"HTMLPreElement":["pre","listing","xmp"],"HTMLQuoteElement":["blockquote","q"],"HTMLSelectedContentElement":["selectedcontent"],"HTMLSourceElement":["source"],"HTMLTimeElement":["time"],"HTMLTitleElement":["title"]}

def generate(model):
    lines = ['// <auto-generated> Static engine conformance from the selected D11 contract. </auto-generated>',
             'module internal NativeApiConformance.Reflection', '', 'open Ranvier.Dom', '',
             'let run (document: Document) =', '    let mutable checks = 0',
             '    let equal label expected actual =', '        checks <- checks + 1',
             '        if expected <> actual then failwith $"{label}: expected {expected}, got {actual}"']
    index = 0
    for interface, tags in TAGS.items():
        setters = [f for f in model['functions'] if f['interface'] == interface and f['kind'] == 'setter']
        for tag in tags:
            var = f'element{index}'
            index += 1
            lines.append(f'    let {var} = document.createElement("{tag}") :?> {interface}')
            lines.append(f'    equal "{tag} tag" "{tag.upper()}" {var}.tagName')
            for setter in setters:
                name = setter['member']
                prop = f'{var}.``{name}``'
                label = tag + '.' + name
                attribute = 'http-equiv' if name == 'httpEquiv' else name.lower()
                kind = setter['arguments'][0]['idl']['name']
                if kind == 'boolean':
                    lines += [f'    {prop} <- true', f'    equal "{label} property" true {prop}',
                              f'    equal "{label} attribute" "" ({var}.getAttribute("{attribute}"))',
                              f'    {var}.removeAttribute("{attribute}")', f'    equal "{label} removal" false {prop}']
                elif setter['parameters'][1]['ctype'] == 'const char*':
                    first = 'https://example.invalid/reflection' if name in ['href', 'src', 'cite'] else 'native-api-λ'
                    second = 'https://example.invalid/reverse' if name in ['href', 'src', 'cite'] else 'reverse-api-β'
                    lines += [f'    {prop} <- "{first}"', f'    equal "{label} property" "{first}" {prop}']
                    if interface == 'HTMLTitleElement' and name == 'text':
                        lines += [f'    equal "{label} text" "{first}" {var}.textContent',
                                  f'    {var}.textContent <- "{second}"', f'    equal "{label} reverse text" "{second}" {prop}']
                    else:
                        lines += [f'    equal "{label} attribute" "{first}" ({var}.getAttribute("{attribute}"))',
                                  f'    {var}.setAttribute("{attribute}", "{second}")',
                                  f'    equal "{label} reverse attribute" "{second}" {prop}']
                else:
                    suffix = 'u' if setter['parameters'][1]['ctype'] == 'uint32_t' else ''
                    lines += [f'    {prop} <- 3{suffix}', f'    equal "{label} property" 3{suffix} {prop}',
                              f'    equal "{label} attribute" "3" ({var}.getAttribute("{attribute}"))',
                              f'    {var}.setAttribute("{attribute}", "7")', f'    equal "{label} reverse attribute" 7{suffix} {prop}']
    for interface, tag, member, child_tag in [('HTMLDataListElement', 'datalist', 'options', 'option'), ('HTMLMapElement', 'map', 'areas', 'area')]:
        lines += [f'    let parent{index} = document.createElement("{tag}") :?> {interface}',
                  f'    let collection{index} = parent{index}.{member}',
                  f'    equal "{tag} initial collection" 0u collection{index}.length',
                  f'    let child{index} = document.createElement("{child_tag}")',
                  f'    parent{index}.appendChild(child{index}) |> ignore',
                  f'    equal "{tag} live append" 1u collection{index}.length',
                  f'    parent{index}.removeChild(child{index}) |> ignore',
                  f'    equal "{tag} live removal" 0u collection{index}.length']
        index += 1
    lines.append('    checks')
    return '\n'.join(lines) + '\n'

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('model', type=pathlib.Path)
    parser.add_argument('output', type=pathlib.Path)
    args = parser.parse_args()
    model = json.loads(args.model.read_text(encoding='utf-8'))
    result = generate(model)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(result, encoding='utf-8', newline='\r\n')

